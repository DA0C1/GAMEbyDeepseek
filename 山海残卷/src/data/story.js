/* 传入 save.data：判断一条卷宗是否已解锁 */
export function archiveKnown(item, data) {
  if (item.known) return true;
  if (!data || !data.seen) return false;
  const lore = data.seen.lore || {};
  if (item.loreKey && lore[item.loreKey]) return true;
  if (item.triggers && item.triggers.some((k) => lore[k])) return true;
  if (item.pageTriggers && item.pageTriggers.some((p) => (data.pages || []).indexOf(p) >= 0)) return true;
  return false;
}
